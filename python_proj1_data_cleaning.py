#df['price_per_unit'].count()

# Group by category and price_per_unit, then get the first valid item name for each group
df['item'] = df['item'].fillna(df.groupby(['category', 'price_per_unit']) ['item'].transform('first'))

# Check how many missing items are left
df['item'].isnull().sum()

