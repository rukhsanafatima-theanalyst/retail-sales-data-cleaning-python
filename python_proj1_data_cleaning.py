# Find customer IDs that have missing quantities
missing_customers = df[df['quantity'].isnull()]['customer_id']

# 1. Recalculate total_spent for complete rows (leaves 604 rows as NaN)
df['total_spent'] = df['price_per_unit'] * df['quantity']

# 2. Add an indicator column flagging missing quantities (1 = missing, 0 = complete)
df['is_missing_quantity'] = df['quantity'].isnull().astype(int)

# 3. Create DataFrame 1 (All 12,575 rows with the flag column included)
df_with_missing = df.copy()

# 4. Create DataFrame 2 (11,971 complete rows, dropping missing quantities)
df_clean = df.dropna(subset=['quantity']).drop(columns=['is_missing_quantity']).copy()

# 5. Verify shapes and missing counts
print("df_with_missing shape:", df_with_missing.shape)

print("df_with_missing flagged rows:", df_with_missing['is_missing_quantity'].sum())

print("df_clean shape:", df_clean.shape)

print("df_clean missing quantities:", df_clean['quantity'].isnull().sum())

# Convert transaction_date to datetime format in both dataframes
df_with_missing['transaction_date'] = pd.to_datetime(df_with_missing['transaction_date'])
df_clean['transaction_date'] = pd.to_datetime(df_clean['transaction_date'])

